/**
 * Якоря даты и времени для проверки качества названия записи.
 *
 * Дисциплина дворца требует, чтобы название несло временной якорь. Проверка была
 * написана под китайский язык (`年`, `今天`, `本周`, `周一`…), из-за чего русская
 * запись с относительной датой («сегодня», «на прошлой неделе») якоря не находила:
 * оценка занижалась, и запись получала подсказку добавить дату, которая уже есть.
 *
 * Слова живут здесь, а не в проверке: это языковые данные. Наборы объединяются,
 * потому что проверка эвристическая и языка названия не знает — принять якорь на
 * любом поддерживаемом языке правильнее, чем промахнуться на своём.
 *
 * @module dsh-kyzmem/i18n/dates
 */

import type { KyzmemLanguage } from './language.ts'

/** Относительные даты и дни недели по языкам. Числовые формы — общие, см. ниже. */
const DATE_WORDS: Readonly<Record<KyzmemLanguage, readonly string[]>> = {
  zh: [
    '今天', '昨天', '明天', '本周', '上周', '下周',
    '周一', '周二', '周三', '周四', '周五', '周六', '周日', '周天',
  ],
  en: [
    'today', 'yesterday', 'tomorrow', 'this week', 'last week', 'next week',
    'this month', 'last month', 'monday', 'tuesday', 'wednesday', 'thursday',
    'friday', 'saturday', 'sunday',
  ],
  ru: [
    'сегодня', 'вчера', 'завтра', 'позавчера', 'послезавтра',
    'на этой неделе', 'на прошлой неделе', 'на следующей неделе',
    'в понедельник', 'во вторник', 'в среду', 'в четверг',
    'в пятницу', 'в субботу', 'в воскресенье',
  ],
}

/** Числовые формы: ISO-подобная дата и китайская запись год-месяц / месяц-день. */
const NUMERIC_DATE = String.raw`\d{4}[-/年.]\s?\d{1,2}|\d{1,2}\s?月\s?\d{1,2}\s?[日号]`

/** Экранирование слова перед подстановкой в регексп. */
function escapeForRegex(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/** Регексп временного якоря: числовые формы плюс относительные слова всех языков. */
export const DATE_ANCHOR: RegExp = new RegExp(
  [NUMERIC_DATE, ...Object.values(DATE_WORDS).flat().map(escapeForRegex)].join('|'),
  'iu',
)
